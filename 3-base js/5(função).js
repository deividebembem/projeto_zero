// Criando uma função
function somar(a,b) {
    return a + b
}
// chamando a função
const soma = somar(2,3)

// Exibidno resultado
console.log(`Soma: ${soma}`)

// Criando a função para subtrair
function subtrair(a,b) {
    return a - b
}
// Chamando a função
const subtracao= subtrair(30,3)
// Resultado da função
console.log(`Subtração: ${subtracao}`)
